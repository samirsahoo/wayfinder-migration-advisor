"""Renders the full graph state into a Markdown report -- the artifact a
human actually walks away with. Kept separate from the agents themselves so
the output format can change without touching any analysis logic."""

from __future__ import annotations

from .models import (
    AdvisoryReport,
    ArchitectureRecommendation,
    CostRoiFinding,
    DiscoveryFinding,
    RiskComplianceFinding,
    SystemProfile,
)

SEVERITY_MARKER = {
    "low": "LOW",
    "medium": "MEDIUM",
    "high": "HIGH",
    "critical": "CRITICAL",
}


def render_markdown(
    profile: SystemProfile,
    discovery: DiscoveryFinding,
    architecture: ArchitectureRecommendation,
    risk: RiskComplianceFinding,
    cost: CostRoiFinding,
    report: AdvisoryReport,
) -> str:
    lines: list[str] = []
    w = lines.append

    w(f"# Migration & Transformation Roadmap: {profile.name}")
    w("")
    w(f"> {report.executive_summary}")
    w("")
    w(f"**Governance status:** `{report.governance.status}`" + (
        f" -- _{report.governance.reviewer_note}_" if report.governance.reviewer_note else ""
    ))
    w("")

    w("## 1. Discovery & Readiness")
    w("")
    w(f"**Readiness score: {discovery.readiness_score}/100**")
    w("")
    w(discovery.summary)
    w("")
    if discovery.complexity_signals:
        w("Complexity signals:")
        for s in discovery.complexity_signals:
            w(f"- {s}")
        w("")
    if discovery.dependency_risks:
        w("Dependency risks:")
        for r in discovery.dependency_risks:
            w(f"- {r}")
        w("")

    w("## 2. Target Architecture")
    w("")
    w(f"**Pattern:** {architecture.migration_pattern.value}  ")
    w(f"**Target platform:** {architecture.target_cloud}")
    w("")
    w(architecture.summary)
    w("")
    w("Candidate service decomposition (starting hypothesis, not a final design):")
    for s in architecture.candidate_services:
        w(f"- `{s}`")
    w("")
    w("Well-Architected pillar notes:")
    for pillar, note in architecture.well_architected_notes.items():
        w(f"- **{pillar}:** {note}")
    w("")

    w("## 3. Risk & Compliance")
    w("")
    w(risk.summary)
    w("")
    if risk.risks:
        w("| ID | Severity | Risk | Mitigation |")
        w("|---|---|---|---|")
        for r in risk.risks:
            w(f"| {r.id} | {SEVERITY_MARKER[r.severity.value]} | {r.description} | {r.mitigation} |")
    else:
        w("No material risks identified.")
    w("")

    w("## 4. Cost & ROI")
    w("")
    w(f"**Effort tier:** {cost.cost_tier.value} (~{cost.estimated_duration_months} months)  ")
    w(f"**Projected efficiency gain:** {cost.projected_efficiency_gain_pct}%")
    w("")
    w(cost.summary)
    w("")

    w("## 5. Roadmap")
    w("")
    for i, phase in enumerate(report.phases, start=1):
        w(f"### Phase {i}: {phase.name} ({phase.duration_weeks} weeks)")
        w("")
        w(phase.goal)
        w("")
        w("Exit criteria:")
        for c in phase.exit_criteria:
            w(f"- [ ] {c}")
        w("")

    w("## 6. Top Risks Carried Into Delivery")
    w("")
    for r in report.top_risks:
        w(f"- **[{SEVERITY_MARKER[r.severity.value]}] {r.id}:** {r.description}")
    w("")

    w("---")
    w("_Generated by Wayfinder, an agentic AI migration advisor. Every number and "
      "recommendation above traces back to a named, inspectable heuristic in the "
      "agent that produced it; nothing here is a black-box guess._")

    return "\n".join(lines)
